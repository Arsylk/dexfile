#!/usr/bin/env python3
"""Generate the "large" fixture sources (fixtures.large.Large, fixtures.large.ManyMethods).

Usage: gen_large.py <java-source-root>   (writes <root>/fixtures/large/*.java)

Large.linearLong : one straight-line method of ~N_LINEAR statements (thousands of instructions)
Large.loopLinear : the same body inside a loop so the back-edge offset exceeds 16 bits (goto/32)
Large.manyLocals : > 16 live registers, forcing move/from16 and /range encodings
Large.hugeLocals : ~300 live registers (>= 256), forcing move/16 encodings
ManyMethods      : > 300 small methods in one class
"""
import os
import sys

N_LINEAR = 4600       # statements; keeps javac's 64 KiB bytecode limit per method
N_METHODS = 350


def linear_body(n, acc="acc", i="i"):
    out = []
    for k in range(n):
        # Vary the constant so nothing folds; mix widths so const/16 and const appear.
        c = (k * 2654435761) & 0x7fffffff if k % 3 else (k % 200) - 100
        out.append(f"        {acc} = {acc} * 31L + (long) ({i} ^ {c});")
    return "\n".join(out)


def many_locals():
    lines = []
    n_int, n_long = 40, 12
    for k in range(n_int):
        lines.append(f"        int i{k} = seed + {k};")
    for k in range(n_long):
        lines.append(f"        long l{k} = seed * {k + 1}L;")
    lines.append("        double d0 = seed * 0.5; double d1 = d0 + 1.0; float f0 = seed * 0.25f;")
    lines.append("        Object o0 = \"obj\"; int[] a0 = new int[]{i0, i1, i2};")
    lines.append("        if (seed < 0) {")
    for k in range(n_int):
        lines.append(f"            i{k} = -i{k};")
    lines.append("        }")
    lines.append("        long r = 0;")
    for k in range(n_int):
        lines.append(f"        r += i{k} * i{(k + 7) % n_int};")
    for k in range(n_long):
        lines.append(f"        r ^= l{k} >>> {k + 1};")
    lines.append("        r += (long) (d0 + d1 + f0) + o0.hashCode() + a0.length;")
    lines.append("        r += Large.consume(i0, i1, i2, i3, i4, i5, i6, i7, i8, i9, l0, l1, d0, d1, o0);")
    lines.append("        r += Large.consume(i39, i38, i37, i36, i35, i34, i33, i32, i31, i30, l11, l10, d1, d0, a0);")
    lines.append("        return r;")
    return "\n".join(lines)


def huge_locals():
    """~300 simultaneously live int locals: registers >= 256 force move/16 and move/from16 shuffles."""
    n = 300
    lines = [f"        int h{k} = seed + {k};" for k in range(n)]
    lines.append("        if (seed < 0) {")
    lines += [f"            h{k} ^= h{(k + 1) % n};" for k in range(n)]
    lines.append("        }")
    lines.append("        int r = 0;")
    lines += [f"        r += h{k} * h{(k + 13) % n};" for k in range(n)]
    lines.append("        return r;")
    return "\n".join(lines)


def large(root):
    src = f"""package fixtures.large;

/** GENERATED by scripts/gen_large.py -- do not edit by hand. */
public class Large {{
    public static long consume(int a, int b, int c, int d, int e, int f, int g, int h, int i, int j,
                               long l0, long l1, double d0, double d1, Object o) {{
        return a + b + c + d + e + f + g + h + i + j + l0 + l1 + (long) d0 + (long) d1 + (o == null ? 0 : 1);
    }}

    /** Many simultaneously live locals: registers > 16, move/from16, invoke-static/range. */
    public static long manyLocals(int seed) {{
{many_locals()}
    }}

    /** ~300 live int locals: registers >= 256, move/16 encodings. */
    public static int hugeLocals(int seed) {{
{huge_locals()}
    }}

    /** Straight-line method with ~{N_LINEAR} statements (several thousand instructions). */
    public static long linearLong(long acc, int i) {{
{linear_body(N_LINEAR)}
        return acc;
    }}

    /** Same body in a loop: back-edge and forward branch offsets exceed 16 bits -> goto/32. */
    public static long loopLinear(int n, boolean skip) {{
        long acc = 7;
        for (int i = 0; i < n; i++) {{
            if (skip) continue;
{linear_body(N_LINEAR)}
        }}
        return acc;
    }}
}}
"""
    with open(os.path.join(root, "Large.java"), "w") as fh:
        fh.write(src)


def many_methods(root):
    methods = []
    for k in range(N_METHODS):
        kind = k % 5
        if kind == 0:
            methods.append(f"    public static int m{k:03d}(int x) {{ return x + {k}; }}")
        elif kind == 1:
            methods.append(f"    public int m{k:03d}() {{ return field + {k}; }}")
        elif kind == 2:
            methods.append(f"    private long m{k:03d}(long x) {{ return x * {k}L; }}")
        elif kind == 3:
            methods.append(f"    public static String m{k:03d}() {{ return \"m{k:03d}\"; }}")
        else:
            methods.append(f"    protected void m{k:03d}(int x) {{ field = x ^ {k}; }}")
    calls = " + ".join(f"m{k:03d}(1)" for k in range(0, N_METHODS, 5))
    src = f"""package fixtures.large;

/** GENERATED by scripts/gen_large.py -- {N_METHODS} small methods. */
public class ManyMethods {{
    public int field;

{chr(10).join(methods)}

    public static int callSome() {{ return {calls}; }}
    public long callPrivate() {{ return m002(1L) + m007(2L) + m012(3L); }}
}}
"""
    with open(os.path.join(root, "ManyMethods.java"), "w") as fh:
        fh.write(src)


def main():
    root = os.path.join(sys.argv[1], "fixtures", "large")
    os.makedirs(root, exist_ok=True)
    large(root)
    many_methods(root)


if __name__ == "__main__":
    main()
